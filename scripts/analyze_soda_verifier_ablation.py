def render_report(payload: dict[str, Any]) -> str:
    lines = [
        "# Verifier-Aware SODA Ablation Report",
        "",
        f"- generated_at: `{payload['generated_at']}`",
        "",
        "## Method",
        "",
        "This report uses a paired label-construction ablation. Student rollout, teacher replay, prompt evidence and verifier records are fixed; only the policy that turns candidates into training labels changes:",
        "",
        "- Raw SODA: always uses teacher output as `chosen` and student output as `rejected`.",
        "- Output-only heuristic: accepts teacher output after JSON/action validity and exact quote checks only.",
        "- Verifier-aware SODA: uses the evidence-only verifier verdict to rebuild the chosen action and reject unsafe student/teacher candidates.",
        "",
        "The data-quality side is a verifier-defined label ablation. It directly measures how much label noise the verifier gate removes under its own evidence-only contract; it is not a substitute for an independent human gold audit. To reduce circularity, the report also includes an output-only negative control and exports compact audit cases for human inspection.",
        "",
        "The model-effect side must be interpreted separately. A strict behavioral ablation requires Raw SODA and Verifier-aware SODA LoRA models evaluated under the same runtime config, question files, decoding settings, GPU count and retrieval-round budget.",
        "",
        "## Data Quality Ablation",
        "",
    ]
    for result in payload["quality_experiments"]:
        lines.extend(render_quality_table(result))
        lines.append("")
    lines.extend(render_model_table(payload["model_effects"]))
    lines.extend([""])
    lines.extend(render_paired_model_probe_table(payload["paired_model_probes"]))
    lines.extend([""])
    lines.extend(render_teacher_score_table(payload["teacher_score_effects"]))
    lines.extend([""])
    lines.extend(render_strict_model_effect_status(payload["model_effects"]))
    return "\n".join(lines) + "\n"


def render_audit_cases(payload: dict[str, Any]) -> str:
    lines = [
        "# Verifier-Aware SODA Audit Cases",
        "",
        "These examples are sampled from paired raw teacher/student outputs and verifier records. They are intended for independent manual inspection of the verifier-defined labels.",
        "",
    ]
    labels = {
        "raw_teacher_unsafe": "Raw teacher chosen would be unsafe",
        "student_better_than_teacher": "Student action is safer than teacher candidate",
        "heuristic_false_accept": "Output-only heuristic false accept",
    }
    for result in payload["quality_experiments"]:
        lines.extend([f"## {result['name']}", ""])
        examples = result.get("examples") if isinstance(result.get("examples"), dict) else {}
        for key, title in labels.items():
            cases = examples.get(key) if isinstance(examples.get(key), list) else []
            lines.extend([f"### {title}", ""])
            if not cases:
                lines.extend(["No cases.", ""])
                continue
            for idx, case in enumerate(cases, start=1):
                lines.extend(
                    [
                        f"{idx}. `{case.get('prompt_key')}` {case.get('round') or ''} {case.get('question')}",
                        f"   - correct/student/teacher action: `{case.get('correct_action')}` / `{case.get('student_action')}` / `{case.get('teacher_action')}`",
                        f"   - student_error/teacher_error/teacher_prior: `{case.get('student_error')}` / `{case.get('teacher_error')}` / `{case.get('teacher_prior')}`",
                        f"   - verifier reason: {case.get('label_reason') or ''}",
                        f"   - evidence preview: {case.get('evidence_brief_preview') or ''}",
                        "",
                    ]
                )
    return "\n".join(lines)


def write_audit_artifacts(output_dir: Path, payload: dict[str, Any]) -> None:
    rows = []
    for result in payload["quality_experiments"]:
        examples = result.get("examples") if isinstance(result.get("examples"), dict) else {}
        for case_type, cases in examples.items():
            if not isinstance(cases, list):
                continue
            for case in cases:
                row = {"experiment": result["name"], "case_type": case_type}
                row.update(case)
                rows.append(row)
    with (output_dir / "audit_cases.jsonl").open("w", encoding="utf-8") as handle:
        for row in rows:
            handle.write(json.dumps(row, ensure_ascii=False) + "\n")
    (output_dir / "audit_cases.md").write_text(render_audit_cases(payload), encoding="utf-8")



def scorer_number(score: dict[str, Any], keys: tuple[str, ...]) -> float | None:
    for key in keys:
        try:
            value = score.get(key)
            if value is not None:
                return float(value)
        except (TypeError, ValueError):
            continue
    return None


def scorer_errors(score: dict[str, Any]) -> set[str]:
    output: set[str] = set()
    for key in ("serious_errors", "errors"):
        values = score.get(key)
        if isinstance(values, list):
            output.update(str(item) for item in values if str(item))
    action_error = str(score.get("action_error") or "")
    if action_error and action_error != "none":
        output.add(action_error)
    error_type = str(score.get("error_type") or "")
    if error_type and error_type != "none":
        output.add(error_type)
    if score.get("unsupported"):
        output.add("unsupported")
    if score.get("contradicted"):
        output.add("contradicted")
    return output


def summarize_teacher_score_pairs(records: list[dict[str, Any]]) -> dict[str, Any]:
    by_key: dict[tuple[str, int], dict[str, dict[str, Any]]] = {}
    for record in records:
        case = record.get("case") if isinstance(record.get("case"), dict) else {}
        run = str(case.get("run_label") or "")
        if run not in {"raw_soda", "verifier_soda"}:
            continue
        dataset = str(case.get("dataset") or "")
        try:
            index = int(case.get("index"))
        except (TypeError, ValueError):
            continue
        by_key.setdefault((dataset, index), {})[run] = record

    paired = [runs for runs in by_key.values() if {"raw_soda", "verifier_soda"} <= set(runs)]
    if not paired:
        return {"paired_count": 0}

    deltas: Counter[str] = Counter()
    numeric_acc: dict[str, list[float]] = {"action": [], "support": [], "reward": []}
    for runs in paired:
        raw_score = runs["raw_soda"].get("score") if isinstance(runs["raw_soda"].get("score"), dict) else {}
        verifier_score = (
            runs["verifier_soda"].get("score") if isinstance(runs["verifier_soda"].get("score"), dict) else {}
        )
        for key, score_keys in {
            "action": ("action_score",),
            "support": ("support_score", "evidence_support"),
            "reward": ("reward_score",),
        }.items():
            raw_value = scorer_number(raw_score, score_keys)
            verifier_value = scorer_number(verifier_score, score_keys)
            if raw_value is not None and verifier_value is not None:
                numeric_acc[key].append(verifier_value - raw_value)

        raw_label = str(raw_score.get("label") or "")
        verifier_label = str(verifier_score.get("label") or "")
        if raw_label == "negative":
            deltas["raw_negative"] += 1
        if verifier_label == "negative":
            deltas["verifier_negative"] += 1
        raw_errors = scorer_errors(raw_score)
        verifier_errors = scorer_errors(verifier_score)
        for error in ("unsupported", "premature_answer", "over_abstain", "contradicted"):
            if error in raw_errors:
                deltas[f"raw_error:{error}"] += 1
            if error in verifier_errors:
                deltas[f"verifier_error:{error}"] += 1

    def avg(values: list[float]) -> float | None:
        return round(sum(values) / len(values), 4) if values else None

    return {
        "paired_count": len(paired),
        "avg_action_delta_verifier_minus_raw": avg(numeric_acc["action"]),
        "avg_support_delta_verifier_minus_raw": avg(numeric_acc["support"]),
        "avg_reward_delta_verifier_minus_raw": avg(numeric_acc["reward"]),
        "raw_negative": deltas["raw_negative"],
        "verifier_negative": deltas["verifier_negative"],
        "raw_unsupported": deltas["raw_error:unsupported"],
        "verifier_unsupported": deltas["verifier_error:unsupported"],
        "raw_premature": deltas["raw_error:premature_answer"],
        "verifier_premature": deltas["verifier_error:premature_answer"],
        "raw_over_abstain": deltas["raw_error:over_abstain"],
        "verifier_over_abstain": deltas["verifier_error:over_abstain"],
    }



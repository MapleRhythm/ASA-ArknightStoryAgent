def project_path(path: str | Path) -> Path:
    value = Path(path)
    return value if value.is_absolute() else PROJECT_ROOT / value


def read_json(path: Path) -> Any:
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def read_jsonl(path: Path) -> list[dict[str, Any]]:
    if not path.exists():
        return []
    rows: list[dict[str, Any]] = []
    with path.open(encoding="utf-8") as handle:
        for line in handle:
            if line.strip():
                rows.append(json.loads(line))
    return rows


def parse_jsonish(value: Any) -> dict[str, Any] | None:
    if isinstance(value, dict):
        return value
    raw = str(value or "").strip()
    if not raw:
        return None
    try:
        payload = json.loads(raw)
        return payload if isinstance(payload, dict) else None
    except json.JSONDecodeError:
        pass
    start = raw.find("{")
    end = raw.rfind("}")
    if start >= 0 and end > start:
        try:
            payload = json.loads(raw[start : end + 1])
            return payload if isinstance(payload, dict) else None
        except json.JSONDecodeError:
            return None
    return None


def action_of(payload: dict[str, Any] | None) -> str:
    return str((payload or {}).get("next_action") or "").strip()


def error_value(verdict: dict[str, Any], key: str) -> str:
    return str(verdict.get(key) or "none").strip()


def is_error(value: str) -> bool:
    return value not in SAFE_ERROR_VALUES


def extract_evidence_brief(prompt: str) -> str:
    match = re.search(
        r"(?s)^evidence_brief:\s*(.*?)(?:\nminirag_hints:|\noutput_schema:|\nfields:|\Z)",
        prompt or "",
        flags=re.MULTILINE,
    )
    return match.group(1).strip() if match else ""


def normalized_text(text: str) -> str:
    return re.sub(r"\s+", "", text or "")


def truncate_text(text: Any, limit: int = TEXT_PREVIEW_CHARS) -> str:
    value = re.sub(r"\s+", " ", str(text or "")).strip()
    if len(value) <= limit:
        return value
    return value[: limit - 1].rstrip() + "..."


def collect_quotes(payload: dict[str, Any] | None) -> list[str]:
    if not isinstance(payload, dict):
        return []
    quotes: list[str] = []

    def add_quote(value: Any) -> None:
        quote = re.sub(r"\s+", " ", str(value or "")).strip()
        if quote:
            quotes.append(quote)

    for key in ("evidence_refs", "refs", "citations"):
        refs = payload.get(key)
        if isinstance(refs, list):
            for item in refs:
                if isinstance(item, dict):
                    add_quote(item.get("quote"))
    facts = payload.get("supported_facts")
    if isinstance(facts, list):
        for fact in facts:
            if not isinstance(fact, dict):
                continue
            refs = fact.get("evidence_refs")
            if isinstance(refs, list):
                for item in refs:
                    if isinstance(item, dict):
                        add_quote(item.get("quote"))
    return quotes


def compact_case(
    record: dict[str, Any],
    pair: dict[str, Any],
    teacher_payload: dict[str, Any] | None,
    student_payload: dict[str, Any] | None,
    verdict: dict[str, Any],
) -> dict[str, Any]:
    return {
        "prompt_key": record.get("prompt_key"),
        "question": record.get("question"),
        "round": record.get("round"),
        "correct_action": verdict.get("correct_action"),
        "student_action": action_of(student_payload),
        "teacher_action": action_of(teacher_payload),
        "student_error": error_value(verdict, "student_action_error"),
        "teacher_error": error_value(verdict, "teacher_action_error"),
        "teacher_prior": bool(verdict.get("teacher_answer_uses_prior_knowledge")),
        "evidence_sufficient": verdict.get("evidence_sufficient"),
        "supported_answer": truncate_text(verdict.get("supported_answer"), 500),
        "label_reason": truncate_text(verdict.get("label_reason"), 500),
        "evidence_brief_preview": truncate_text(extract_evidence_brief(str(pair.get("user_prompt") or ""))),
        "student_output_preview": truncate_text(pair.get("student_output")),
        "teacher_output_preview": truncate_text(pair.get("teacher_output")),
    }


def heuristic_accepts_teacher(pair: dict[str, Any], teacher_payload: dict[str, Any] | None) -> tuple[bool, str]:
    if not pair.get("teacher_valid", True):
        return False, "invalid_json"
    teacher_action = action_of(teacher_payload)
    if teacher_action not in ALLOWED_ACTIONS:
        return False, "invalid_action"
    quotes = collect_quotes(teacher_payload)
    if quotes:
        evidence = normalized_text(extract_evidence_brief(str(pair.get("user_prompt") or "")))
        missing = [quote for quote in quotes if normalized_text(quote) not in evidence]
        if missing:
            return False, "quote_not_in_evidence"
    return True, "accepted"


def load_raw_pairs(raw_dirs: list[Path]) -> dict[str, dict[str, Any]]:
    pairs: dict[str, dict[str, Any]] = {}
    for raw_dir in raw_dirs:
        for pair in read_jsonl(raw_dir / "raw_pairs.jsonl"):
            prompt_key = str(pair.get("prompt_key") or "")
            if prompt_key and prompt_key not in pairs:
                pairs[prompt_key] = pair
    return pairs


def load_verifier_records(verifier_dir: Path) -> list[dict[str, Any]]:
    rows = []
    for record in read_jsonl(verifier_dir / "api_verifier_records.jsonl"):
        verdict = record.get("verifier")
        if record.get("error") or not isinstance(verdict, dict):
            continue
        correct_action = str(verdict.get("correct_action") or "").strip()
        if correct_action in ALLOWED_ACTIONS:
            rows.append(record)
    return rows


def count_dataset_relabels(verifier_dir: Path) -> dict[str, Any]:
    records = []
    for filename in ("train.json", "val.json"):
        payload = read_json(verifier_dir / filename)
        if isinstance(payload, list):
            records.extend(payload)
    stats: Counter[str] = Counter()
    chosen_action_mismatch = 0
    chosen_total = 0
    for record in records:
        if record.get("task_type") != "conclusion_generation":
            continue
        meta = record.get("meta") if isinstance(record.get("meta"), dict) else {}
        reason = str(meta.get("api_verifier_reason") or "")
        if reason:
            stats[f"reason:{reason}"] += 1
        if bool(record.get("kto_tag")) and reason.startswith("verifier_chosen_"):
            chosen_total += 1
            payload = None
            conversations = record.get("conversations")
            if isinstance(conversations, list) and conversations:
                payload = parse_jsonish(conversations[-1].get("value"))
            if action_of(payload) != str(meta.get("verifier_correct_action") or ""):
                chosen_action_mismatch += 1
    return {
        "conclusion_verifier_chosen": chosen_total,
        "conclusion_chosen_action_mismatch": chosen_action_mismatch,
        "reason_counts": dict(sorted(stats.items())),
    }


def analyze_quality_experiment(name: str, raw_dirs: list[Path], verifier_dir: Path) -> dict[str, Any]:
    pairs = load_raw_pairs(raw_dirs)
    verifier_records = load_verifier_records(verifier_dir)
    stats: Counter[str] = Counter()
    teacher_errors: Counter[str] = Counter()
    student_errors: Counter[str] = Counter()
    heuristic_drop_reasons: Counter[str] = Counter()
    examples: dict[str, list[dict[str, Any]]] = {
        "raw_teacher_unsafe": [],
        "student_better_than_teacher": [],
        "heuristic_false_accept": [],
    }

    for record in verifier_records:
        prompt_key = str(record.get("prompt_key") or "")
        verdict = record.get("verifier") if isinstance(record.get("verifier"), dict) else {}
        pair = pairs.get(prompt_key)
        if pair is None:
            stats["missing_raw_pair"] += 1
            continue
        stats["prompts"] += 1
        correct_action = str(verdict.get("correct_action") or "").strip()
        teacher_payload = parse_jsonish(pair.get("teacher_output"))
        student_payload = parse_jsonish(pair.get("student_output"))
        teacher_action = action_of(teacher_payload)
        student_action = action_of(student_payload)
        teacher_error = error_value(verdict, "teacher_action_error")
        student_error = error_value(verdict, "student_action_error")
        teacher_prior = bool(verdict.get("teacher_answer_uses_prior_knowledge"))
        teacher_errors[teacher_error] += 1
        student_errors[student_error] += 1

        teacher_unsafe = (
            not pair.get("teacher_valid", True)
            or teacher_action not in ALLOWED_ACTIONS
            or teacher_action != correct_action
            or is_error(teacher_error)
            or teacher_prior
        )
        student_unsafe = (
            not pair.get("student_valid", True)
            or student_action not in ALLOWED_ACTIONS
            or student_action != correct_action
            or is_error(student_error)
        )
        if teacher_action != correct_action:
            stats["raw_teacher_action_mismatch"] += 1
        if student_action != correct_action:
            stats["student_action_mismatch"] += 1
        if teacher_unsafe:
            stats["raw_teacher_unsafe_chosen"] += 1
            if len(examples["raw_teacher_unsafe"]) < EXAMPLE_LIMIT:
                examples["raw_teacher_unsafe"].append(
                    compact_case(record, pair, teacher_payload, student_payload, verdict)
                )
        if not student_unsafe and teacher_unsafe:
            stats["student_better_than_teacher"] += 1
            if len(examples["student_better_than_teacher"]) < EXAMPLE_LIMIT:
                examples["student_better_than_teacher"].append(
                    compact_case(record, pair, teacher_payload, student_payload, verdict)
                )
        if teacher_prior:
            stats["raw_teacher_prior_leak"] += 1
        if teacher_error in {"unsupported_answer", "teacher_prior_knowledge"} or teacher_prior:
            stats["raw_teacher_unsupported_or_prior"] += 1
        if teacher_error == "premature_answer":
            stats["raw_teacher_premature_answer"] += 1
        if teacher_error == "over_retrieve":
            stats["raw_teacher_over_retrieve"] += 1
        if student_error == "premature_answer":
            stats["student_premature_answer"] += 1
        if student_error == "unsupported_answer":
            stats["student_unsupported_answer"] += 1
        if student_error == "over_retrieve":
            stats["student_over_retrieve"] += 1

        accepted, drop_reason = heuristic_accepts_teacher(pair, teacher_payload)
        heuristic_drop_reasons[drop_reason] += 1
        if accepted:
            stats["heuristic_teacher_accepted"] += 1
            if teacher_unsafe:
                stats["heuristic_unsafe_accepted"] += 1
                if len(examples["heuristic_false_accept"]) < EXAMPLE_LIMIT:
                    examples["heuristic_false_accept"].append(
                        compact_case(record, pair, teacher_payload, student_payload, verdict)
                    )
            if teacher_error in {"unsupported_answer", "teacher_prior_knowledge"} or teacher_prior:
                stats["heuristic_unsupported_or_prior_accepted"] += 1
        elif teacher_unsafe:
            stats["heuristic_unsafe_dropped"] += 1

    relabels = count_dataset_relabels(verifier_dir)
    return {
        "name": name,
        "raw_dirs": [str(path.relative_to(PROJECT_ROOT)) if path.is_relative_to(PROJECT_ROOT) else str(path) for path in raw_dirs],
        "verifier_dir": str(verifier_dir.relative_to(PROJECT_ROOT)) if verifier_dir.is_relative_to(PROJECT_ROOT) else str(verifier_dir),
        "stats": dict(stats),
        "teacher_error_counts": dict(sorted(teacher_errors.items())),
        "student_error_counts": dict(sorted(student_errors.items())),
        "heuristic_drop_reasons": dict(sorted(heuristic_drop_reasons.items())),
        "relabels": relabels,
        "examples": examples,
    }


def rate(numerator: int | float, denominator: int | float) -> float | None:
    if not denominator:
        return None
    return round(float(numerator) / float(denominator), 4)


def raw_rate(numerator: int | float, denominator: int | float) -> float | None:
    if not denominator:
        return None
    return float(numerator) / float(denominator)


def count_rate(count: int, denominator: int) -> str:
    return f"{count} ({md_rate(rate(count, denominator))})"


def relative_reduction(before: int, after: int) -> str:
    if before <= 0:
        return "n/a"
    return md_rate(rate(before - after, before))


def percentage_point_delta(before: int, after: int, denominator: int) -> str:
    before_rate = raw_rate(before, denominator) or 0.0
    after_rate = raw_rate(after, denominator) or 0.0
    return f"{(before_rate - after_rate) * 100:.2f} pp"


def final_action(row: dict[str, Any]) -> str:
    trace = row.get("retrieval_trace")
    if isinstance(trace, list) and trace:
        last = trace[-1] if isinstance(trace[-1], dict) else {}
        return str(last.get("planner_action") or "")
    return str(row.get("final_action") or "")


def summarize_rows(rows: list[dict[str, Any]], name: str) -> dict[str, Any]:
    counter: Counter[str] = Counter()
    action_sequences: Counter[str] = Counter()
    elapsed = []
    marker_re = re.compile("|".join(re.escape(item) for item in ABSTAIN_MARKERS))
    for row in rows:
        counter["count"] += 1
        if row.get("error"):
            counter["errors"] += 1
        if marker_re.search(str(row.get("answer") or "")) or final_action(row) == "abstain":
            counter["abstain_like"] += 1
        action = final_action(row)
        counter[f"final_action:{action}"] += 1
        trace = row.get("retrieval_trace")
        if isinstance(trace, list) and trace:
            seq = ">".join(str((item or {}).get("planner_action") or "") for item in trace if isinstance(item, dict))
        else:
            seq = action
        action_sequences[seq] += 1
        try:
            elapsed.append(float(row.get("elapsed_sec")))
        except (TypeError, ValueError):
            pass
    return {
        "name": name,
        "count": counter["count"],
        "errors": counter["errors"],
        "abstain_like": counter["abstain_like"],
        "final_actions": {
            key.split(":", 1)[1]: value
            for key, value in sorted(counter.items())
            if key.startswith("final_action:")
        },
        "action_sequences": dict(sorted(action_sequences.items())),
        "avg_elapsed_sec": round(sum(elapsed) / len(elapsed), 3) if elapsed else None,
    }


def summarize_eval_path(path: Path) -> dict[str, Any]:
    if path.is_file():
        rows = read_jsonl(path)
        dataset_name = "hard10" if "hard10" in path.name else "eval50" if "eval50" in path.name else path.stem
        return {"source": path.name, "summaries": [summarize_rows(rows, dataset_name)] if rows else []}
    summaries = []
    for name in ("eval50", "hard10"):
        rows = read_jsonl(path / f"{name}_answers.jsonl")
        if rows:
            summaries.append(summarize_rows(rows, name))
    if summaries:
        return {"source": "answers.jsonl", "summaries": summaries}
    summary = read_json(path / "summary.json")
    if isinstance(summary, dict) and isinstance(summary.get("summaries"), list):
        return {"source": "summary.json", "summaries": summary["summaries"]}
    return {"source": "answers.jsonl", "summaries": summaries}


def runtime_summary_status(summary: dict[str, Any], *, expected_count: int | None = None) -> str:
    count = int(summary.get("count") or 0)
    errors = int(summary.get("errors") or 0)
    final_actions = summary.get("final_actions") if isinstance(summary.get("final_actions"), dict) else {}
    non_empty_actions = sum(int(value) for key, value in final_actions.items() if str(key).strip())
    if count <= 0:
        return "invalid: empty output"
    if expected_count is not None and count < expected_count:
        return f"incomplete: {count}/{expected_count}"
    if errors >= count:
        return "invalid: all rows failed"
    if errors:
        return f"partial: {errors}/{count} rows failed"
    if non_empty_actions == 0:
        return "invalid: no parsed final action"
    return "valid behavioral evidence"


def collect_model_effects(model_evals: list[dict[str, str]]) -> list[dict[str, Any]]:
    output = []
    for item in model_evals:
        path = project_path(item["path"])
        if not path.exists():
            output.append({"name": item["name"], "path": item["path"], "missing": True, "note": item.get("note", "")})
            continue
        payload = summarize_eval_path(path)
        payload.update({"name": item["name"], "path": item["path"], "missing": False, "note": item.get("note", "")})
        output.append(payload)
    return output



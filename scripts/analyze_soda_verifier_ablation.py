def summarize_paired_model_probe(item: dict[str, str]) -> dict[str, Any]:
    raw_path = project_path(item["raw_path"])
    verifier_path = project_path(item["verifier_path"])
    raw_rows = load_eval_rows(raw_path)
    verifier_rows = load_eval_rows(verifier_path)
    raw_by_q = {str(row.get("question") or ""): row for row in raw_rows}
    verifier_by_q = {str(row.get("question") or ""): row for row in verifier_rows}
    questions = [question for question in raw_by_q if question and question in verifier_by_q]
    stats: Counter[str] = Counter()
    action_pairs: Counter[str] = Counter()
    examples = []
    marker_re = re.compile("|".join(re.escape(item) for item in ABSTAIN_MARKERS))

    for question in questions:
        raw = raw_by_q[question]
        verifier = verifier_by_q[question]
        raw_action = final_action(raw)
        verifier_action = final_action(verifier)
        action_pairs[f"{raw_action or '<empty>'}->{verifier_action or '<empty>'}"] += 1
        if raw.get("error"):
            stats["raw_errors"] += 1
        if verifier.get("error"):
            stats["verifier_errors"] += 1
        raw_abstain_like = raw_action == "abstain" or bool(marker_re.search(str(raw.get("answer") or "")))
        verifier_abstain_like = verifier_action == "abstain" or bool(marker_re.search(str(verifier.get("answer") or "")))
        if raw_abstain_like:
            stats["raw_abstain_like"] += 1
        if verifier_abstain_like:
            stats["verifier_abstain_like"] += 1
        stats[f"raw_action:{raw_action}"] += 1
        stats[f"verifier_action:{verifier_action}"] += 1
        if raw_action != verifier_action:
            stats["action_changed"] += 1
            if len(examples) < EXAMPLE_LIMIT:
                examples.append(
                    {
                        "question": question,
                        "raw_action": raw_action,
                        "verifier_action": verifier_action,
                        "raw_answer": truncate_text(raw.get("answer"), 360),
                        "verifier_answer": truncate_text(verifier.get("answer"), 360),
                    }
                )

    status = "valid behavioral probe"
    if not questions:
        status = "invalid: no overlapping questions"
    elif stats["raw_errors"] or stats["verifier_errors"]:
        status = f"invalid: runtime errors raw={stats['raw_errors']} verifier={stats['verifier_errors']}"
    elif action_pairs and set(action_pairs) == {"<empty>-><empty>"}:
        status = "invalid: no parsed final actions"

    return {
        "name": item["name"],
        "raw_label": item["raw_label"],
        "raw_path": item["raw_path"],
        "verifier_label": item["verifier_label"],
        "verifier_path": item["verifier_path"],
        "note": item.get("note", ""),
        "evidence_status": status,
        "paired_count": len(questions),
        "stats": dict(stats),
        "action_pairs": dict(sorted(action_pairs.items())),
        "raw_runtime": runtime_signature(raw_rows[0]) if raw_rows else {},
        "verifier_runtime": runtime_signature(verifier_rows[0]) if verifier_rows else {},
        "examples": examples,
    }


